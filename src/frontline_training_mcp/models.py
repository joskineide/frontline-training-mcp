"""ORM mapping of the schema.

The SQL migrations are the source of truth; this is only a mapping of them, and
tests/test_db.py fails if the two drift apart. There is deliberately no relationship()
anywhere: every load is an explicit query inside a tenant-scoped transaction, so nothing
can be loaded implicitly later, outside that scope.
"""

from datetime import date, datetime
from typing import Any

from sqlalchemy import BigInteger, Computed, Date, DateTime, Identity, Integer, Text, func, text
from sqlalchemy.dialects.postgresql import JSONB, TSVECTOR
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column


class Base(DeclarativeBase):
    pass


class Tenant(Base):
    __tablename__ = "tenant"

    tenant_id: Mapped[str] = mapped_column(Text, primary_key=True)
    name: Mapped[str] = mapped_column(Text)


class Team(Base):
    __tablename__ = "team"

    tenant_id: Mapped[str] = mapped_column(Text, primary_key=True)
    team_id: Mapped[str] = mapped_column(Text, primary_key=True)
    name: Mapped[str] = mapped_column(Text)
    manager_id: Mapped[str] = mapped_column(Text)


class AppUser(Base):
    __tablename__ = "app_user"

    tenant_id: Mapped[str] = mapped_column(Text, primary_key=True)
    user_id: Mapped[str] = mapped_column(Text, primary_key=True)
    team_id: Mapped[str | None] = mapped_column(Text)
    display_name: Mapped[str] = mapped_column(Text)
    role: Mapped[str] = mapped_column(Text)
    external_subject: Mapped[str | None] = mapped_column(Text)


class Module(Base):
    __tablename__ = "module"

    tenant_id: Mapped[str] = mapped_column(Text, primary_key=True)
    module_id: Mapped[str] = mapped_column(Text, primary_key=True)
    title: Mapped[str] = mapped_column(Text)
    summary: Mapped[str] = mapped_column(Text)
    content: Mapped[str] = mapped_column(Text)
    duration_minutes: Mapped[int] = mapped_column(Integer)
    # Generated by Postgres (see the migration); never written by the application.
    search_vector: Mapped[Any | None] = mapped_column(
        TSVECTOR,
        Computed(
            "setweight(to_tsvector('english', title), 'A')"
            " || setweight(to_tsvector('english', summary), 'B')"
            " || setweight(to_tsvector('english', content), 'C')",
            persisted=True,
        ),
    )


class Assignment(Base):
    __tablename__ = "assignment"

    tenant_id: Mapped[str] = mapped_column(Text, primary_key=True)
    assignment_id: Mapped[int] = mapped_column(BigInteger, Identity(always=True), primary_key=True)
    worker_id: Mapped[str] = mapped_column(Text)
    module_id: Mapped[str] = mapped_column(Text)
    assigned_by: Mapped[str] = mapped_column(Text)
    due_date: Mapped[date | None] = mapped_column(Date)
    assigned_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )
    completed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class Announcement(Base):
    __tablename__ = "announcement"

    tenant_id: Mapped[str] = mapped_column(Text, primary_key=True)
    announcement_id: Mapped[int] = mapped_column(
        BigInteger, Identity(always=True), primary_key=True
    )
    team_id: Mapped[str] = mapped_column(Text)
    author_id: Mapped[str] = mapped_column(Text)
    title: Mapped[str] = mapped_column(Text)
    body: Mapped[str] = mapped_column(Text)
    status: Mapped[str] = mapped_column(Text, server_default=text("'draft'"))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    published_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    published_by: Mapped[str | None] = mapped_column(Text)


class AuditLog(Base):
    __tablename__ = "audit_log"

    audit_id: Mapped[int] = mapped_column(BigInteger, Identity(always=True), primary_key=True)
    tenant_id: Mapped[str] = mapped_column(Text)
    actor_id: Mapped[str] = mapped_column(Text)
    tool: Mapped[str] = mapped_column(Text)
    target: Mapped[dict[str, Any]] = mapped_column(JSONB, server_default=text("'{}'"))
    outcome: Mapped[str] = mapped_column(Text)
    at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    trace_id: Mapped[str | None] = mapped_column(Text)
